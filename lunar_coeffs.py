def get_max_degree():
    """Return the maximum degree available in the coefficient set."""
    max_n = 0
    for (n, m) in C_NORM:
        if n > max_n:
            max_n = n
    return max_n


def get_coefficients(max_degree=10):
    """Return C and S coefficient arrays up to given degree.

    Returns (C, S) as 2D numpy arrays of shape (max_degree+1, max_degree+1).
    """
    import numpy as np
    C = np.zeros((max_degree + 1, max_degree + 1))
    S = np.zeros((max_degree + 1, max_degree + 1))

    for (n, m), val in C_NORM.items():
        if n <= max_degree:
            C[n, m] = val
    for (n, m), val in S_NORM.items():
        if n <= max_degree:
            S[n, m] = val

    return C, S
